package com.example.nexus.domain.model

/**
 * IntentType enum representing the four types of user posts on Nexus
 */
enum class IntentType {
    LOOKING_FOR,    // Seeking teammates, study partners, collaborators
    HAPPENING,      // Events, sports, socials, meetups
    ASKING,         // Polls, questions, opinions
    OFFERING        // Tutoring, skills, items, help
}
